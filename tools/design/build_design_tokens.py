#!/usr/bin/env python3
"""Generate runtime constants app/ui/theme/tokens.gd from docs/design/tokens.json.

tokens.json is the single source of truth; never edit tokens.gd by hand.
Use --check in tests/CI to fail when the generated file is stale.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/design/tokens.json'
TARGET = ROOT / 'app/ui/theme/tokens.gd'


def name(*parts):
    return '_'.join(parts).replace('.', '_').upper()


def render():
    tokens = json.loads(SOURCE.read_text())
    lines = ['extends RefCounted', '# Generated by tools/design/build_design_tokens.py from docs/design/tokens.json. Do not edit.',
             'const VERSION = "%s"' % tokens['version']]
    for key, value in tokens['color'].items():
        lines.append('const %s = Color("%s")' % (name(key), value.lstrip('#').lower()))
    lines.append('const COLORS = {' + ', '.join('"%s": %s' % (name(k), name(k)) for k in tokens['color']) + '}')
    for key, value in tokens['metric'].items():
        lines.append('const %s = %d' % (name(key), value))
    for key, value in tokens['type'].items():
        if isinstance(value, int):
            lines.append('const %s = %d' % (name('font', key), value))
    for key, value in tokens['motion_ms'].items():
        lines.append('const %s = %s' % (name('motion', key), repr(value / 1000)))
    for key, value in tokens['focus_feedback'].items():
        lines.append('const %s = %s' % (name('focus', key), repr(value)))
    haptic = {k: [v['ms'], v['amplitude']] for k, v in tokens['haptic'].items() if isinstance(v, dict)}
    lines.append('const HAPTIC = ' + json.dumps(haptic))
    lines.append('const SKY_ANCHORS = ' + json.dumps([[a['hour'], a['top'].lstrip('#'), a['bottom'].lstrip('#')] for a in tokens['sky_anchors']]))
    buttons = {k: {f: (name(c) if c else '') for f, c in v.items()} for k, v in tokens['button'].items()}
    lines.append('# kind -> token constant names; resolved by party_theme.gd')
    lines.append('const BUTTON = ' + json.dumps(buttons))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            sys.exit('app/ui/theme/tokens.gd is stale; run python3 tools/design/build_design_tokens.py')
        print('PASS design tokens: runtime constants match docs/design/tokens.json')
    else:
        TARGET.write_text(text)
        print(TARGET)
